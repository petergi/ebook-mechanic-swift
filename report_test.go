// TestGenerateMarkdownReport tests report generation
func TestGenerateMarkdownReport(t *testing.T) {
	tempDir := t.TempDir()

	result := &ScanResult{
		TotalFiles:        100,
		CorruptedFiles:    []CorruptedFile{},
		EPUBTotal:         50,
		EPUBCorrupted:     2,
		MOBITotal:         30,
		MOBICorrupted:     1,
		PDFTotal:          20,
		PDFCorrupted:      0,
		EmptyFolders:      []string{},
		TotalFolders:      10,
		FoldersWithEbooks: 8,
	}

	reportPath, err := GenerateMarkdownReport(result, tempDir, "CORRUPTED")

	if err != nil {
		t.Fatalf("GenerateMarkdownReport failed: %v", err)
	}

	// Check that report file was created
	if _, err := os.Stat(reportPath); os.IsNotExist(err) {
		t.Errorf("Expected report file to be created at %s", reportPath)
	}

	// Read report content
	content, err := os.ReadFile(reportPath)
	if err != nil {
		t.Fatalf("Failed to read report: %v", err)
	}

	contentStr := string(content)

	// Verify report contains key sections
	if !strings.Contains(contentStr, "# EbookMechanic Report") {
		t.Error("Expected report to contain title")
	}

	if !strings.Contains(contentStr, "Corruption Scan Summary") {
		t.Error("Expected report to contain corruption summary")
	}

	if !strings.Contains(contentStr, "Empty Folders Summary") {
		t.Error("Expected report to contain empty folders summary")
	}

	if !strings.Contains(contentStr, "**Total files scanned:** 100") {
		t.Error("Expected report to contain total files count")
	}

	if !strings.Contains(contentStr, "*Report generated by EbookMechanic*") {
		t.Error("Expected report to contain footer")
	}
}

