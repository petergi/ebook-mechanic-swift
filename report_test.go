// TestFilterByExt tests the filterByExt helper function
func TestFilterByExt(t *testing.T) {
	files := []CorruptedFile{
		{Path: "/path/to/book1.epub", Reason: "test", Size: 100},
		{Path: "/path/to/book2.mobi", Reason: "test", Size: 200},
		{Path: "/path/to/book3.epub", Reason: "test", Size: 300},
		{Path: "/path/to/book4.pdf", Reason: "test", Size: 400},
	}

	epubFiles := filterByExt(files, ".epub")
	if len(epubFiles) != 2 {
		t.Errorf("Expected 2 EPUB files, got %d", len(epubFiles))
	}

	mobiFiles := filterByExt(files, ".mobi")
	if len(mobiFiles) != 1 {
		t.Errorf("Expected 1 MOBI file, got %d", len(mobiFiles))
	}

	pdfFiles := filterByExt(files, ".pdf")
	if len(pdfFiles) != 1 {
		t.Errorf("Expected 1 PDF file, got %d", len(pdfFiles))
	}

	azw3Files := filterByExt(files, ".azw3")
	if len(azw3Files) != 0 {
		t.Errorf("Expected 0 AZW3 files, got %d", len(azw3Files))
	}
}

// TestFormatBytes tests the formatBytes helper function
func TestFormatBytes(t *testing.T) {
	tests := []struct {
		bytes    int64
		expected string
	}{
		{0, "0 B"},
		{100, "100 B"},
		{1023, "1023 B"},
		{1024, "1.0 KB"},
		{1536, "1.5 KB"},
		{1048576, "1.0 MB"},
		{1572864, "1.5 MB"},
		{1073741824, "1.0 GB"},
		{1099511627776, "1.0 TB"},
	}

	for _, test := range tests {
		result := formatBytes(test.bytes)
		if result != test.expected {
			t.Errorf("formatBytes(%d) = %s, expected %s", test.bytes, result, test.expected)
		}
	}
}

// TestReportFilename tests that report filename includes timestamp
